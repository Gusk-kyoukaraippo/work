import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('操作パネル');
sheet.showGridLines = false;
sheet.getRange('A1:K32').format = { fill: '#F7F9FB', font: { name: 'Yu Gothic', size: 12, color: '#17324D' }, rowHeight: 24, verticalAlignment: 'center' };
sheet.getRange('A:A').format.columnWidth = 3;
sheet.getRange('K:K').format.columnWidth = 3;
sheet.getRange('B:J').format.columnWidth = 10;
function block(range, text, fill, size = 12, bold = false, color = '#17324D', align = 'left') {
  const r = sheet.getRange(range); r.merge();
  sheet.getRange(range.split(':')[0]).values = [[text]];
  r.format = { fill, font: { name: 'Yu Gothic', size, bold, color }, horizontalAlignment: align, verticalAlignment: 'center', wrapText: true };
}
block('B2:J3', 'Excelゲート', '#F7F9FB', 24, true);
block('B5:J8', 'はじめに一度だけ設定します\nフォルダ一式を全員が使う共有場所に置いてから、下のボタンを押してください。', '#FFF5CC', 14);
// Assembly replaces this placeholder with a real shape bound to InitializeGate.
block('B14:J16', '初回設定', '#1769AA', 14, true, '#FFFFFF', 'center');
block('B22:J25', '設定後は「編集する」からEdgeを開きます。\n入力を終えたらこのブックへ戻り、「保存して終了」を押します。', '#EDF4FA', 12);
workbook.recalculate();
await fs.mkdir(path.join(root, 'workbook'), { recursive: true });
async function render(name) {
  const blob = await workbook.render({ sheetName: '操作パネル', range: 'A1:K32', scale: 1.5, format: 'png' });
  await fs.writeFile(path.join(root, 'workbook', name + '.png'), new Uint8Array(await blob.arrayBuffer()));
}
await render('MVP5th-setup-preview');
await (await SpreadsheetFile.exportXlsx(workbook)).save(path.join(root, 'workbook/MVP5th-template.xlsx'));
// Layout reference only. The shipped operation panel is generated by GatePanel.bas.
block('B5:J8', 'Edgeで入力中です。ブックは開いたままにしてください。\nEdgeで「入力を終える」を押したら、ここで「保存して終了」を押します。', '#EDF4FA', 13);
for (const [range, label, fill] of [
  ['B10:F12', '編集する', '#1769AA'], ['G10:J12', '閲覧する', '#5B748B'],
  ['B14:J16', '保存して終了', '#147A55'], ['B18:F20', '保存して続ける', '#5B748B'],
  ['G18:J20', '閉じる', '#5B748B'], ['B27:F28', '使い方', '#5B748B'], ['G27:J28', '保存履歴（管理者）', '#5B748B']
]) block(range, label, fill, 14, true, '#FFFFFF', 'center');
block('B22:J25', '通常：Edgeで「入力を終える」 → ブックで「保存して終了」\n途中：Edgeで「途中保存の準備」 → ブックで「保存して続ける」', '#EDF4FA', 11);
block('B30:J31', '最終保存：2026/09/21 10:00　保存者：確認用', '#F7F9FB', 11);
workbook.recalculate();
await render('MVP5th-operation-panel-preview');
const errors = await workbook.inspect({ kind: 'match', searchTerm: '#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!', options: { useRegex: true, maxResults: 10 }, maxChars: 1000 });
