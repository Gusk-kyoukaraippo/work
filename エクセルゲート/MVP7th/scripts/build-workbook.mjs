import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let workbook, sheet;
// Maintenance template and layout references only. Never writes the native .xlsm.
function resetPanel() {
  workbook = Workbook.create();
  sheet = workbook.worksheets.add('操作パネル');
  sheet.showGridLines = false;
  sheet.getRange('A1:K32').format = { fill: '#F7F9FB', font: { name: 'Yu Gothic', size: 12, color: '#17324D' }, rowHeight: 24, verticalAlignment: 'center' };
  sheet.getRange('A:A').format.columnWidth = 3;
  sheet.getRange('K:K').format.columnWidth = 3;
  sheet.getRange('B:J').format.columnWidth = 10;
  block('B2:J3', 'Excelゲート', '#F7F9FB', 24, true);
}
function block(range, text, fill, size = 12, bold = false, color = '#17324D', align = 'left') {
  const r = sheet.getRange(range); r.merge();
  sheet.getRange(range.split(':')[0]).values = [[text]];
  r.format = { fill, font: { name: 'Yu Gothic', size, bold, color }, horizontalAlignment: align, verticalAlignment: 'center', wrapText: true };
}
resetPanel();
block('B5:J8', 'はじめに一度だけ設定します\nフォルダ一式を全員が使う共有場所に置いてから、下のボタンを押してください。', '#FFF5CC', 14);
// Assembly replaces this placeholder with a real shape bound to InitializeGate.
block('B14:J16', '初回設定', '#1769AA', 14, true, '#FFFFFF', 'center');
block('B22:J25', '設定後は操作パネルからEdgeを開きます。\nCSVフォルダ閲覧型では、初回にローカルまたは共有フォルダのパスを登録します。', '#EDF4FA', 12);
workbook.recalculate();
console.log((await workbook.inspect({ kind: 'table', range: '操作パネル!B22:J25', include: 'values,formulas', tableMaxRows: 4, tableMaxCols: 9, maxChars: 1000 })).ndjson);
await fs.mkdir(path.join(root, 'workbook'), { recursive: true });
async function render(name) {
  const blob = await workbook.render({ sheetName: '操作パネル', range: 'A1:K32', scale: 1.5, format: 'png' });
  await fs.writeFile(path.join(root, 'workbook', name + '.png'), new Uint8Array(await blob.arrayBuffer()));
}
await render('MVP7th-setup-preview');
const templateWorkbook = workbook;
// CSV-folder layout reference only. The shipped panel is generated by GatePanel.bas.
// The path is set on the deployed workbook, not in this template.
resetPanel();
block('B5:J8', '「最新CSVで開く」で登録フォルダから読み込みます。\nCSVは書き換えません。集計結果をブックへ保存する操作は不要です。', '#EDF4FA', 12);
for (const [range, label, fill] of [
  ['B10:J13', '最新CSVで開く', '#1769AA'],
  ['B16:F18', '読込先の設定', '#5B748B'], ['G16:J18', '閉じる', '#5B748B'],
  ['B27:J28', '使い方', '#5B748B']
]) block(range, label, fill, 14, true, '#FFFFFF', 'center');
block('B21:J25', 'CSV読込先：\n（初回設定で登録するフォルダ）', '#EDF4FA', 11);
block('B30:J31', 'CSV更新後は、もう一度「最新CSVで開く」を押してください。', '#F7F9FB', 11);
workbook.recalculate();
await render('MVP7th-csv-panel-preview');
const errors = await workbook.inspect({ kind: 'match', searchTerm: '#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!', options: { useRegex: true, maxResults: 10 }, maxChars: 1000 });
console.log(errors.ndjson);
await (await SpreadsheetFile.exportXlsx(templateWorkbook)).save(path.join(root, 'workbook/MVP7th-template.xlsx'));
console.log('Built the maintenance template and setup/CSV layout previews. No native .xlsm was modified; macro assembly and target-machine execution are separate steps.');
