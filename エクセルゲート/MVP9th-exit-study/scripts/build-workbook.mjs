import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let workbook, sheet;
// Maintenance template and layout references only. Never writes the native .xlsm.
function resetPanel(title = 'Excelゲート') {
  workbook = Workbook.create();
  sheet = workbook.worksheets.add('操作パネル');
  sheet.showGridLines = false;
  sheet.getRange('A1:K32').format = { fill: '#F7F9FB', font: { name: 'Yu Gothic', size: 12, color: '#17324D' }, rowHeight: 24, verticalAlignment: 'center' };
  sheet.getRange('A:A').format.columnWidth = 3;
  sheet.getRange('K:K').format.columnWidth = 3;
  sheet.getRange('B:J').format.columnWidth = 10;
  block('B2:J3', title, '#F7F9FB', 20, true);
  block('B4:J4', 'DX推進委員会 Excelゲート', '#F7F9FB', 10, false, '#5B748B');
}
function block(range, text, fill, size = 12, bold = false, color = '#17324D', align = 'left') {
  const r = sheet.getRange(range); r.merge();
  sheet.getRange(range.split(':')[0]).values = [[text]];
  r.format = { fill, font: { name: 'Yu Gothic', size, bold, color }, horizontalAlignment: align, verticalAlignment: 'center', wrapText: true };
}
resetPanel();
block('B6:J9', 'この場所を保存先として登録します。\nフォルダ一式をこれから使う場所に置き、下の「初回設定」を押してください。', '#F7F9FB', 14);
// Assembly replaces this placeholder with a real shape bound to InitializeGate.
block('B10:J12', '初回設定', '#1769AA', 16, true, '#FFFFFF', 'center');
block('B15:J17', '設定後は「編集する」からEdgeを開きます。\n保存済みのデータを残して、あとから設定を見直すこともできます。', '#F7F9FB', 12);
workbook.recalculate();
console.log((await workbook.inspect({ kind: 'table', range: '操作パネル!B15:J17', include: 'values,formulas', tableMaxRows: 4, tableMaxCols: 9, maxChars: 1000 })).ndjson);
await fs.mkdir(path.join(root, 'workbook'), { recursive: true });
async function render(name) {
  const blob = await workbook.render({ sheetName: '操作パネル', range: 'A1:K32', scale: 1.5, format: 'png' });
  await fs.writeFile(path.join(root, 'workbook', name + '.png'), new Uint8Array(await blob.arrayBuffer()));
}
await render('MVP9th-setup-preview');
const templateWorkbook = workbook;
// CSV-folder layout reference only. The shipped panel is generated by GatePanel.bas.
// The path is set on the deployed workbook, not in this template.
resetPanel('地ケア・病床機能指標モニター');
block('B6:J9', '「最新CSVで開く」で登録フォルダから読み込みます。\nCSVは書き換えません。集計結果をブックへ保存する操作は不要です。', '#F7F9FB', 14);
for (const [range, label, fill] of [
  ['B10:J12', '最新CSVで開く', '#1769AA'],
  ['B15:F16', '読込先の設定', '#ECF0F4'], ['G15:J16', '閉じる', '#ECF0F4'],
  ['B22:F23', '使い方', '#ECF0F4'], ['G22:J23', '設定を見直す', '#ECF0F4']
]) block(range, label, fill, fill === '#1769AA' ? 16 : 12, fill === '#1769AA', fill === '#1769AA' ? '#FFFFFF' : '#405E77', 'center');
block('B18:J20', 'CSV読込先：\n（初回設定で登録するフォルダ）', '#F7F9FB', 11);
block('B26:J27', 'CSV更新後は、もう一度「最新CSVで開く」を押してください。', '#F7F9FB', 11);
